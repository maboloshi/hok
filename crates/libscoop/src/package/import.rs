//! Parse a Scoopfile — the document `scoop export` / `hok export` produce —
//! into the pieces `hok import` replays.
//!
//! Two shapes are accepted:
//!
//! - **Upstream** (`libexec/scoop-export.ps1`): `buckets` and `apps` are arrays
//!   of objects carrying `Name`/`Source`/… and `Name`/`Version`/`Source`/
//!   `Updated`/`Info`;
//! - **Legacy hok**: `buckets` is a `name → url` map and `apps` a
//!   `bucket → { name: version }` map (hok's own export before it emitted the
//!   upstream shape; the pre-`apps` variant that nested the apps under
//!   `buckets` is still recognized).
//!
//! This module only *reads* the document: mapping the entries onto config
//! writes, bucket clones and install queries belongs to the caller, and the
//! decisions it needs (which official config keys hok has, how `Source`
//! becomes an install query) are pure functions here so they can be tested
//! without a session.

use serde_json::{Map, Value};

use crate::constant::{AUTO_GENERATED_SOURCE, INFO_FAILED, INFO_GLOBAL, INFO_HELD};
use crate::error::Fallible;

/// One `buckets[]` entry of a Scoopfile.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ImportBucket {
    /// Bucket name.
    pub name: String,
    /// Git remote URL for upstream git buckets, the local path otherwise.
    pub source: String,
}

/// hok's per-app extension (`apps[].Hok`, written by `hok export --hok`).
///
/// Explicit state instead of the human-readable `Info` words; when present it
/// is authoritative for the app it belongs to.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct HokAppState {
    pub hold: bool,
    pub global: bool,
    pub architecture: Option<String>,
    pub failed: bool,
}

/// One `apps[]` entry of a Scoopfile.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ImportApp {
    /// App name.
    pub name: String,
    /// Recorded version (used for `<auto-generated>` sources only, as upstream).
    pub version: Option<String>,
    /// `apps[].Source`: origin bucket name, `<auto-generated>`, or the manifest
    /// URL / local path.
    pub source: Option<String>,
    /// Upstream's `Info` words, split on `", "`.
    pub info: Vec<String>,
    /// hok's extension for this app, when the Scoopfile carries one.
    pub hok: Option<HokAppState>,
}

impl ImportApp {
    /// Whether upstream recorded the app as a global install.
    pub fn is_global(&self) -> bool {
        self.flag(|hok| hok.global, INFO_GLOBAL)
    }

    /// Whether upstream recorded the app as held.
    pub fn is_held(&self) -> bool {
        self.flag(|hok| hok.hold, INFO_HELD)
    }

    /// Whether upstream recorded the app as a failed install.
    pub fn is_failed(&self) -> bool {
        self.flag(|hok| hok.failed, INFO_FAILED)
    }

    /// The architecture upstream recorded, if it differs from the default.
    pub fn architecture(&self) -> Option<&str> {
        match &self.hok {
            Some(hok) => hok.architecture.as_deref(),
            None => self
                .info
                .iter()
                .find(|word| is_architecture_word(word))
                .map(String::as_str),
        }
    }

    /// A flag from hok's extension when the Scoopfile has one, otherwise from
    /// upstream's `Info` words.
    fn flag(&self, from_hok: impl Fn(&HokAppState) -> bool, word: &str) -> bool {
        match &self.hok {
            Some(hok) => from_hok(hok),
            None => self.info.iter().any(|w| w == word),
        }
    }
}

/// One `hok.aliases[]` entry of hok's extension.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ImportAlias {
    /// Alias name (the name given to `hok alias add`).
    pub name: String,
    /// The alias command as written; `None` when the exporting machine had a
    /// config entry whose script was already gone.
    pub command: Option<String>,
    /// The alias's `# Summary:` line.
    pub summary: Option<String>,
}

/// A whole Scoopfile.
#[derive(Debug, Clone, Default)]
pub struct ImportFile {
    /// Upstream's `config` section (`scoop export -c`): key → value.
    pub config: Map<String, Value>,
    /// hok's `hok.config` extension: hok's own keys, verbatim.
    pub hok_config: Map<String, Value>,
    /// hok's `hok.aliases` extension: aliases with their commands.
    pub hok_aliases: Vec<ImportAlias>,
    /// Buckets to add.
    pub buckets: Vec<ImportBucket>,
    /// Apps to install.
    pub apps: Vec<ImportApp>,
}

/// Parse a Scoopfile.
///
/// # Errors
///
/// Returns an error if the content is neither valid JSON nor JSON5 (see
/// [`crate::internal::json`]); upstream reads the same file with `parse_json`
/// (`libexec/scoop-import.ps1:19`).
pub fn parse_import_json(content: &str) -> Fallible<ImportFile> {
    let root: Value = crate::internal::json::parse_str(content)?;
    let mut file = ImportFile::default();

    if let Some(object) = root.get("config").and_then(Value::as_object) {
        file.config = object.clone();
    }
    let hok = root.get("hok");
    if let Some(object) = hok
        .and_then(|hok| hok.get("config"))
        .and_then(Value::as_object)
    {
        file.hok_config = object.clone();
    }
    if let Some(entries) = hok
        .and_then(|hok| hok.get("aliases"))
        .and_then(Value::as_array)
    {
        file.hok_aliases = entries.iter().filter_map(hok_alias).collect();
    }

    parse_buckets(&root, &mut file);
    parse_apps(&root, &mut file);
    Ok(file)
}

/// One `hok.aliases[]` entry.
fn hok_alias(entry: &Value) -> Option<ImportAlias> {
    let object = entry.as_object()?;
    let name = object.get("Name").and_then(Value::as_str)?;
    if name.is_empty() {
        return None;
    }
    Some(ImportAlias {
        name: name.to_owned(),
        command: object
            .get("Command")
            .and_then(Value::as_str)
            .map(str::to_owned),
        summary: object
            .get("Summary")
            .and_then(Value::as_str)
            .map(str::to_owned),
    })
}

/// `buckets`: an upstream array, or hok's legacy `name → url` map.
fn parse_buckets(root: &Value, file: &mut ImportFile) {
    match root.get("buckets") {
        Some(Value::Array(entries)) => {
            file.buckets = entries
                .iter()
                .filter_map(|entry| {
                    let object = entry.as_object()?;
                    let name = object.get("Name").and_then(Value::as_str)?;
                    if name.is_empty() {
                        return None;
                    }
                    Some(ImportBucket {
                        name: name.to_owned(),
                        source: object
                            .get("Source")
                            .and_then(Value::as_str)
                            .unwrap_or_default()
                            .to_owned(),
                    })
                })
                .collect();
        }
        Some(Value::Object(map)) => {
            file.buckets = map
                .iter()
                .filter_map(|(name, value)| {
                    // A string value is a bucket url; an object is the legacy
                    // `bucket → { app: version }` map, not a bucket entry.
                    value.as_str().map(|source| ImportBucket {
                        name: name.clone(),
                        source: source.to_owned(),
                    })
                })
                .collect();
        }
        _ => {}
    }
}

/// `apps`: an upstream array, or hok's legacy `bucket → { name: version }`
/// map — which older files nested under `buckets` instead.
///
/// An upstream entry without a `Name` (or with an empty one) is dropped: it
/// cannot be addressed, let alone installed.
fn parse_apps(root: &Value, file: &mut ImportFile) {
    match root.get("apps") {
        Some(Value::Array(entries)) => {
            file.apps = entries.iter().filter_map(upstream_app).collect();
        }
        Some(Value::Object(map)) => legacy_apps(map, &mut file.apps),
        _ => {}
    }
    if file.apps.is_empty()
        && let Some(Value::Object(map)) = root.get("buckets")
    {
        legacy_apps(map, &mut file.apps);
    }
}

/// One upstream `apps[]` entry.
fn upstream_app(entry: &Value) -> Option<ImportApp> {
    let object = entry.as_object()?;
    let name = object.get("Name").and_then(Value::as_str)?;
    if name.is_empty() {
        return None;
    }
    Some(ImportApp {
        name: name.to_owned(),
        version: object
            .get("Version")
            .and_then(Value::as_str)
            .map(str::to_owned),
        source: object
            .get("Source")
            .and_then(Value::as_str)
            .map(str::to_owned),
        info: object
            .get("Info")
            .and_then(Value::as_str)
            .map(split_info)
            .unwrap_or_default(),
        hok: object.get("Hok").and_then(hok_app_state),
    })
}

/// A legacy `bucket → { name: version }` map.
fn legacy_apps(map: &Map<String, Value>, out: &mut Vec<ImportApp>) {
    for (bucket, apps) in map {
        let Some(apps) = apps.as_object() else {
            continue;
        };
        for (name, version) in apps {
            out.push(ImportApp {
                name: name.clone(),
                version: version.as_str().map(str::to_owned),
                source: Some(bucket.clone()),
                info: Vec::new(),
                hok: None,
            });
        }
    }
}

/// Upstream's `Info` is `', '`-joined (`libexec/scoop-list.ps1:58`).
fn split_info(info: &str) -> Vec<String> {
    info.split(", ")
        .filter(|word| !word.is_empty())
        .map(str::to_owned)
        .collect()
}

/// hok's per-app extension object.
fn hok_app_state(value: &Value) -> Option<HokAppState> {
    let object = value.as_object()?;
    Some(HokAppState {
        hold: object.get("Hold").and_then(Value::as_bool).unwrap_or(false),
        global: object
            .get("Global")
            .and_then(Value::as_bool)
            .unwrap_or(false),
        architecture: object
            .get("Architecture")
            .and_then(Value::as_str)
            .map(str::to_owned),
        failed: object
            .get("Failed")
            .and_then(Value::as_bool)
            .unwrap_or(false),
    })
}

/// Whether an `Info` word is an architecture name (the only word that is not a
/// fixed label).
fn is_architecture_word(word: &str) -> bool {
    matches!(
        word.to_ascii_lowercase().as_str(),
        "64bit" | "32bit" | "arm64"
    )
}

/// The install query an entry replays, mirroring upstream
/// `scoop-import.ps1:52-58`: `bucket/name` when the source is one of the
/// Scoopfile's buckets, `name@version` for a generated user manifest,
/// otherwise the source (a manifest URL or local path) as it stands.
///
/// Returns `None` when a `<auto-generated>` entry carries no version — there
/// is nothing to generate a manifest from.
pub fn install_query(app: &ImportApp, bucket_names: &[String]) -> Option<String> {
    match app.source.as_deref() {
        Some(source) if bucket_names.iter().any(|name| name == source) => {
            Some(format!("{source}/{}", app.name))
        }
        Some(AUTO_GENERATED_SOURCE) => app
            .version
            .as_deref()
            .map(|version| format!("{}@{version}", app.name)),
        Some(source) => Some(source.to_owned()),
        // No source recorded (a failed install): fall back to the bare name so
        // the bucket lookup decides, like upstream's empty `$app`.
        None => Some(app.name.clone()),
    }
}

/// Whether a Scoopfile bucket source is a git remote hok can clone.
///
/// Upstream keeps non-git buckets under their local path
/// (`lib/buckets.ps1:112-115`); hok's `bucket add` is git-remote only, so such
/// entries are reported as skipped instead of being handed to `git clone`.
pub fn is_git_remote(source: &str) -> bool {
    source.contains("://") || source.starts_with("git@")
}

/// Whether an app's `Source` names a bucket that is not available, which makes
/// the entry impossible to replay.
///
/// Upstream falls back to installing the bare source in that case
/// (`libexec/scoop-import.ps1:57`), which fails the same way ("Couldn't find
/// manifest for '<bucket>'") — reporting it as a skip explains the failure
/// instead of leaving a resolve error behind. A source that is a URL, a path,
/// or a manifest file name is not a bucket name and never matches.
pub fn is_unavailable_bucket(source: &str, bucket_names: &[String]) -> bool {
    !source.is_empty()
        && source != AUTO_GENERATED_SOURCE
        && !bucket_names.iter().any(|name| name == source)
        && !source.contains(['/', '\\', ':', '.'])
}

/// Render a Scoopfile config value as the string `hok config set` takes.
///
/// Returns `None` for values hok has no representation for (arrays/objects,
/// e.g. `alias` or `private-hosts`).
pub fn config_value_to_string(value: &Value) -> Option<String> {
    match value {
        Value::String(text) => Some(text.clone()),
        Value::Bool(flag) => Some(flag.to_string()),
        Value::Number(number) => Some(number.to_string()),
        Value::Null => Some(String::new()),
        Value::Array(_) | Value::Object(_) => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn parse(content: &str) -> ImportFile {
        parse_import_json(content).unwrap()
    }

    /// Upstream's document: arrays, `Info` words, and the extension when the
    /// file came from `hok export --hok`.
    #[test]
    fn parses_upstream_shape() {
        let file = parse(
            r#"{
                "buckets": [
                    { "Name": "main", "Source": "https://github.com/ScoopInstaller/Main", "Updated": "x", "Manifests": 3 }
                ],
                "apps": [
                    {
                        "Name": "7zip", "Version": "26.03", "Source": "main", "Updated": "x", "Info": "",
                        "Hok": { "Hold": true, "Global": false, "Architecture": "32bit", "Failed": false }
                    },
                    { "Name": "vcredist", "Version": "2022", "Source": "extras", "Updated": "x", "Info": "Global install, Held package" }
                ]
            }"#,
        );

        assert_eq!(file.buckets.len(), 1);
        assert_eq!(file.buckets[0].name, "main");
        assert_eq!(
            file.buckets[0].source,
            "https://github.com/ScoopInstaller/Main"
        );

        assert_eq!(file.apps.len(), 2);
        let seven = &file.apps[0];
        assert_eq!(seven.name, "7zip");
        assert_eq!(seven.source.as_deref(), Some("main"));
        // The extension is authoritative when present.
        assert!(seven.is_held());
        assert!(!seven.is_global());
        assert_eq!(seven.architecture(), Some("32bit"));

        // Without an extension the `Info` words are read instead.
        let vcredist = &file.apps[1];
        assert!(vcredist.hok.is_none());
        assert!(vcredist.is_global());
        assert!(vcredist.is_held());
        assert!(!vcredist.is_failed());
        assert_eq!(vcredist.architecture(), None);
    }

    /// hok's legacy map shape, including the oldest variant that nested the
    /// apps under `buckets`.
    #[test]
    fn parses_legacy_hok_shape() {
        let file = parse(
            r#"{
                "buckets": { "main": "https://github.com/ScoopInstaller/Main" },
                "apps": { "main": { "7zip": "26.03", "aria2": "1.37.0-1" } }
            }"#,
        );
        assert_eq!(file.buckets.len(), 1);
        assert_eq!(
            file.buckets[0].source,
            "https://github.com/ScoopInstaller/Main"
        );
        let names: Vec<&str> = file.apps.iter().map(|a| a.name.as_str()).collect();
        assert_eq!(names, vec!["7zip", "aria2"]);
        assert_eq!(file.apps[0].source.as_deref(), Some("main"));
        assert_eq!(file.apps[0].version.as_deref(), Some("26.03"));

        let nested = parse(r#"{ "buckets": { "extras": { "everything": "1.4.1" } } }"#);
        assert_eq!(nested.apps.len(), 1);
        assert_eq!(nested.apps[0].name, "everything");
        assert_eq!(nested.apps[0].source.as_deref(), Some("extras"));
    }

    /// The `config` sections: upstream's keys, and hok's verbatim ones.
    #[test]
    fn parses_config_sections() {
        let no_config = parse(r#"{"buckets":[],"apps":[]}"#);
        assert!(no_config.config.is_empty());
        assert!(no_config.hok_config.is_empty());

        let file = parse(
            r#"{
                "config": { "proxy": "127.0.0.1:7890", "aria2-split": 5 },
                "hok": {
                    "version": 1,
                    "config": { "use_sqlite_cache": true },
                    "aliases": [
                        { "Name": "rt", "Command": "scoop reinstall $args", "Summary": "Reinstall" },
                        { "Name": "gone", "Command": null }
                    ]
                },
                "buckets": [], "apps": []
            }"#,
        );
        assert_eq!(file.config.len(), 2);
        assert_eq!(file.config["proxy"], "127.0.0.1:7890");
        assert_eq!(file.hok_config.len(), 1);
        assert_eq!(file.hok_config["use_sqlite_cache"], true);
        assert_eq!(file.hok_aliases.len(), 2);
        assert_eq!(file.hok_aliases[0].name, "rt");
        assert_eq!(
            file.hok_aliases[0].command.as_deref(),
            Some("scoop reinstall $args")
        );
        assert_eq!(file.hok_aliases[0].summary.as_deref(), Some("Reinstall"));
        // A config entry whose script was already gone carries no command.
        assert_eq!(file.hok_aliases[1].command, None);
    }

    /// Upstream's `Source` → install query mapping.
    #[test]
    fn install_query_follows_upstream() {
        let buckets = vec!["main".to_owned(), "extras".to_owned()];
        let app = |source: Option<&str>, version: Option<&str>| ImportApp {
            name: "app".to_owned(),
            version: version.map(str::to_owned),
            source: source.map(str::to_owned),
            info: Vec::new(),
            hok: None,
        };

        assert_eq!(
            install_query(&app(Some("main"), Some("1.0")), &buckets).as_deref(),
            Some("main/app")
        );
        assert_eq!(
            install_query(&app(Some(AUTO_GENERATED_SOURCE), Some("1.0")), &buckets).as_deref(),
            Some("app@1.0")
        );
        assert_eq!(
            install_query(&app(Some("https://example.com/app.json"), None), &buckets).as_deref(),
            Some("https://example.com/app.json")
        );
        assert_eq!(
            install_query(&app(None, None), &buckets).as_deref(),
            Some("app")
        );
        // `<auto-generated>` without a version cannot be replayed.
        assert_eq!(
            install_query(&app(Some(AUTO_GENERATED_SOURCE), None), &buckets),
            None
        );
    }

    /// A source that can only be a bucket name is reported when that bucket is
    /// not available; URLs, paths, manifest file names and `<auto-generated>`
    /// are left to the installer.
    #[test]
    fn unavailable_bucket_is_only_a_bare_name() {
        let buckets = vec!["main".to_owned()];
        assert!(is_unavailable_bucket("missing", &buckets));
        assert!(!is_unavailable_bucket("main", &buckets));
        assert!(!is_unavailable_bucket(
            "https://example.com/app.json",
            &buckets
        ));
        assert!(!is_unavailable_bucket("C:\\manifests\\app.json", &buckets));
        assert!(!is_unavailable_bucket("app.json", &buckets));
        assert!(!is_unavailable_bucket(AUTO_GENERATED_SOURCE, &buckets));
        assert!(!is_unavailable_bucket("", &buckets));
    }

    /// Upstream's canonical key spellings — the ones its own `get_config` calls
    /// read, i.e. underscores except the hyphenated `aria2-*` family — map onto
    /// hok, the machine-specific ones are refused, and the other separator is
    /// tolerated for a hand-written Scoopfile.
    #[test]
    fn config_keys_map_onto_hok() {
        use crate::config::{OfficialKey, map_official_key};

        assert_eq!(map_official_key("proxy"), OfficialKey::Supported("proxy"));
        assert_eq!(
            map_official_key("use_sqlite_cache"),
            OfficialKey::Supported("use_sqlite_cache")
        );
        assert_eq!(
            map_official_key("ignore_running_processes"),
            OfficialKey::Supported("ignore_running_processes")
        );
        assert_eq!(
            map_official_key("no_junction"),
            OfficialKey::Supported("no_junction")
        );
        assert_eq!(
            map_official_key("aria2-min-split-size"),
            OfficialKey::Supported("aria2-min-split-size")
        );
        assert_eq!(
            map_official_key("use-sqlite-cache"),
            OfficialKey::Supported("use_sqlite_cache")
        );
        assert_eq!(map_official_key("root_path"), OfficialKey::MachineSpecific);
        assert_eq!(map_official_key("root-path"), OfficialKey::MachineSpecific);
        assert_eq!(map_official_key("scoop_repo"), OfficialKey::Unsupported);
        assert_eq!(
            map_official_key("aria2-warning-enabled"),
            OfficialKey::Unsupported
        );

        assert_eq!(
            config_value_to_string(&serde_json::json!(true)).as_deref(),
            Some("true")
        );
        assert_eq!(
            config_value_to_string(&serde_json::json!(5)).as_deref(),
            Some("5")
        );
        assert_eq!(config_value_to_string(&serde_json::json!(["a"])), None);
    }

    /// Only a URL-ish or `git@` source may be handed to `git clone`.
    #[test]
    fn git_remote_detection() {
        assert!(is_git_remote("https://github.com/ScoopInstaller/Main"));
        assert!(is_git_remote("git@github.com:ScoopInstaller/Main.git"));
        assert!(is_git_remote("ssh://git@example.com/repo"));
        assert!(!is_git_remote("D:\\Scoop\\buckets\\local"));
        assert!(!is_git_remote("\\\\server\\share\\bucket"));
        assert!(!is_git_remote("main"));
        assert!(!is_git_remote(""));
    }

    /// Upstream reads this file with `parse_json`, so hand-edited syntax (a
    /// BOM, comments, trailing commas) must not be rejected here. The
    /// tolerance contract itself lives in [`crate::internal::json`].
    #[test]
    fn parse_accepts_hand_edited_syntax() {
        let content = "\u{FEFF}{\n  // exported by scoop\n  \"apps\": [ { \"Name\": \"7zip\", \"Source\": \"main\", } ]\n}";
        let file = parse(content);
        assert_eq!(file.apps.len(), 1);
        assert_eq!(file.apps[0].name, "7zip");
    }

    #[test]
    fn parse_invalid_json_errors() {
        assert!(parse_import_json("{ not json").is_err());
    }
}
