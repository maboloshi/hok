fn main() {
    use time::OffsetDateTime;
    use time::macros::format_description;

    let now = OffsetDateTime::now_local().unwrap_or_else(|_| OffsetDateTime::now_utc());
    let date = now
        .format(&format_description!(
            "[year]-[month]-[day] [hour]:[minute]:[second] [offset_hour sign:mandatory][offset_minute]"
        ))
        .expect("static format description cannot fail");
    println!("cargo:rustc-env=BUILD_DATE={}", date);

    // Windows gives the process's main thread the 1 MiB stack reserved in the
    // PE header (`SizeOfStackReserve`), and that reservation cannot be changed
    // at run time. A debug build of the CLI already peaks well above it: the
    // clap command tree, the nested async command chain and the serde manifest
    // parse reached ~1.2 MiB for a plain local manifest, so
    // `hok download <manifest>` died with STATUS_STACK_OVERFLOW (0xC00000FD)
    // before it opened a single connection. Reserve a real stack instead; the
    // reservation is virtual memory, committed only as the stack grows.
    //
    // MSVC only: `/STACK:` is a link.exe / lld-link flag (the workspace builds
    // for `*-pc-windows-msvc`), and older GNU-ld-style linkers would read it as
    // an input file.
    if std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc") {
        println!("cargo:rustc-link-arg=/STACK:8388608");
    }

    // Command registration: scan src/cmd/ for command module files
    generate_cmd_mods().expect("failed to generate cmd_mods.rs");
}

/// Auto-discover command modules in src/cmd/ and generate mod declarations.
///
/// Scans `src/cmd/*.rs`, excluding `mod.rs`, and writes a generated
/// file to `src/cmd/__cmd_reg__.rs` with `mod xxx;` lines.
/// Adding a new command = drop a file in `src/cmd/`, no manual registration.
///
/// The file is included via `include!` from `cmd/mod.rs`, so the `mod`
/// declarations inside it resolve to `src/cmd/xxx.rs` correctly.
fn generate_cmd_mods() -> std::io::Result<()> {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    let cmd_dir = std::path::Path::new(&manifest_dir).join("src/cmd");

    let mut mods: Vec<String> = Vec::new();
    if cmd_dir.is_dir() {
        for entry in std::fs::read_dir(&cmd_dir)? {
            let entry = entry?;
            let path = entry.path();
            if path.extension().is_none_or(|e| e != "rs") {
                continue;
            }
            let stem = path.file_stem().unwrap().to_string_lossy();
            // Skip mod.rs and any generated file
            if stem == "mod" || stem.starts_with("__") {
                continue;
            }
            mods.push(stem.to_string());
        }
    }

    mods.sort();

    let mut output = String::from("// Auto-generated by build.rs — do not edit manually.\n");
    output.push_str("// Add a .rs file to src/cmd/ to register a new command.\n\n");
    for m in &mods {
        output.push_str(&format!("pub(crate) mod {m};\n"));
    }

    let dest = cmd_dir.join("__cmd_reg__.rs");
    std::fs::write(&dest, output)?;

    println!("cargo:rerun-if-changed=src/cmd/");
    Ok(())
}
