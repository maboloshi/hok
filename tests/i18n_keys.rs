//! i18n consistency safety net (Plan A)
//!
//! The **static half** of the i18n guard: everything that can be checked
//! without running the CLI lives here, so it stays fast enough for the inner
//! loop. `tests/cli_help_i18n.rs` is the end-to-end half (it spawns the
//! binary and renders every command's help).
//!
//! Reconciliation of five invariants to prevent drift between the translation
//! files, the build-time flattening and the source code:
//! 1. en.yml and zh.yml must have exactly the same leaf keys (a missing
//!    translation or a dropped key fails the test);
//! 2. every literal t!("key") used in the source must exist in both en and zh
//!    (a typo or a missing key fails the test);
//! 3. dead keys (defined in the yml but never referenced from the source)
//!    are reported as warnings without blocking the build -- because some keys
//!    are referenced indirectly through variables or through an Error's
//!    Display impl, which a literal scan cannot statically prove dead;
//! 4. the tables generated by `crates/hok-i18n/build.rs` still carry the YAML
//!    corner-case semantics the rust-i18n migration had to preserve (`|-`
//!    block scalars, `\n` escapes, flow sequences) -- see
//!    [`yaml_flattening_survives_the_build_script`]. `build.rs` is a build
//!    script, so cargo never compiles it as a test target: this test checks its
//!    *product* through the public `hok_i18n::t!` API instead;
//! 5. every long description a Rust doc comment documents has a `long_about`
//!    key in both tables (see [`documented_long_help_is_translated`]). Without
//!    the key the derive patches `long_about` with the translated short
//!    `about`, so the doc comment's second paragraph is rendered in *neither*
//!    locale -- which is how `create`, `search`, `auto_pr`, `virustotal` and
//!    `shim add` silently lost theirs.
//!
//! Design trade-offs:
//! - Pure std implementation (no regex dependency); self-contained and fast;
//! - Only **leaf keys** (keys with a value or a block scalar) are reconciled;
//!   intermediate namespace keys (with no translation value) are skipped;
//! - Block scalar (|- / >) content lines are not treated as keys.
//!
//! Run: cargo test -p hok --test i18n_keys (also covered by a full cargo test).

use std::collections::BTreeSet;
use std::fs;
use std::path::Path;

/// Extract all leaf key paths (e.g. output.done) from YAML source.
/// Handles 2-space indentation, block scalars (|/>), ignores comments and
/// blank lines.
fn extract_leaf_keys(src: &str) -> BTreeSet<String> {
    let mut leaves = BTreeSet::new();
    let mut stack: Vec<(usize, String)> = Vec::new();
    let mut in_block: Option<usize> = None;

    for raw in src.split('\n') {
        let raw = raw.trim_end_matches('\r');
        // Skip block-scalar content lines (more indented than the block key).
        if let Some(block_indent) = in_block {
            let indent = leading_spaces(raw);
            if raw.trim().is_empty() {
                continue;
            }
            if indent > block_indent {
                continue;
            }
            in_block = None;
        }

        let trimmed = raw.trim();
        if trimmed.is_empty() || trimmed.starts_with('#') {
            continue;
        }
        let Some(colon_idx) = raw.find(':') else {
            continue;
        };
        let name = raw[..colon_idx].trim();
        if name.is_empty()
            || !name
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '.' || c == '-')
        {
            continue;
        }
        let indent = leading_spaces(raw);
        while stack.last().map(|(i, _)| *i >= indent).unwrap_or(false) {
            stack.pop();
        }
        let rest = raw[colon_idx + 1..].trim();
        let is_block = rest.starts_with('|') || rest.starts_with('>');
        stack.push((indent, name.to_string()));
        if !rest.is_empty() {
            leaves.insert(
                stack
                    .iter()
                    .map(|(_, n)| n.as_str())
                    .collect::<Vec<_>>()
                    .join("."),
            );
        }
        if is_block {
            in_block = Some(indent);
        }
    }
    leaves
}

fn leading_spaces(s: &str) -> usize {
    s.len() - s.trim_start_matches(' ').len()
}

fn collect_rs_files(dir: &Path, out: &mut Vec<String>) {
    if let Ok(entries) = fs::read_dir(dir) {
        for e in entries.flatten() {
            let p = e.path();
            if p.is_dir() {
                collect_rs_files(&p, out);
            } else if p.extension().and_then(|e| e.to_str()) == Some("rs") {
                out.push(p.to_string_lossy().into_owned());
            }
        }
    }
}

/// Strip comments (//, ///, //!, /* */) from Rust source.
/// Note: **string literals are preserved** -- the t!("key") key lives inside
/// a string, so it must not be stripped.
fn strip_comments(src: &str) -> Vec<char> {
    let chars: Vec<char> = src.chars().collect();
    let mut out: Vec<char> = Vec::with_capacity(chars.len());
    let mut i = 0;
    let mut in_line_comment = false;
    let mut in_block_comment = false;
    while i < chars.len() {
        if in_line_comment {
            if chars[i] == '\n' {
                in_line_comment = false;
                out.push('\n');
            }
            i += 1;
            continue;
        }
        if in_block_comment {
            if chars[i] == '*' && i + 1 < chars.len() && chars[i + 1] == '/' {
                in_block_comment = false;
                i += 2;
            } else {
                if chars[i] == '\n' {
                    out.push('\n');
                }
                i += 1;
            }
            continue;
        }
        if chars[i] == '/' && i + 1 < chars.len() && chars[i + 1] == '/' {
            in_line_comment = true;
            i += 2;
            continue;
        }
        if chars[i] == '/' && i + 1 < chars.len() && chars[i + 1] == '*' {
            in_block_comment = true;
            i += 2;
            continue;
        }
        out.push(chars[i]);
        i += 1;
    }
    out
}

/// Collect literal t!("key") keys from comment-free code.
fn scan_literal_t_keys(src: &str) -> BTreeSet<String> {
    let code = strip_comments(src);
    let mut keys = BTreeSet::new();
    let mut i = 0;
    while i < code.len() {
        let Some(pos) = find_macro_call(&code, i) else {
            break;
        };
        let quote = code[pos..].iter().position(|&c| c == '"');
        let Some(q) = quote else {
            i = pos + 2;
            continue;
        };
        let ks = pos + q + 1;
        let ke = code[ks..].iter().position(|&c| c == '"');
        let Some(e) = ke else {
            i = pos + 2;
            continue;
        };
        let key: String = code[ks..ks + e].iter().collect();
        if !key.is_empty()
            && key
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '.' || c == '-')
        {
            keys.insert(key);
        }
        i = ks + e + 1;
    }
    keys
}

/// Find the next t! macro name from `from` (must be preceded by a
/// non-identifier boundary).
fn find_macro_call(src: &[char], from: usize) -> Option<usize> {
    let mut search_from = from;
    loop {
        let idx = src[search_from..]
            .iter()
            .position(|&c| c == 't')
            .map(|p| p + search_from)?;
        if idx + 1 < src.len() && src[idx + 1] == '!' {
            let preceded_ok =
                idx == 0 || !(src[idx - 1].is_ascii_alphanumeric() || src[idx - 1] == '_');
            if preceded_ok {
                return Some(idx);
            }
        }
        search_from = idx + 1;
    }
}

fn run_consistency() {
    let manifest_dir = env!("CARGO_MANIFEST_DIR");
    let locales = Path::new(manifest_dir).join("locales");
    let en_src = fs::read_to_string(locales.join("en.yml")).expect("failed to read locales/en.yml");
    let zh_src = fs::read_to_string(locales.join("zh.yml")).expect("failed to read locales/zh.yml");
    let en_keys = extract_leaf_keys(&en_src);
    let zh_keys = extract_leaf_keys(&zh_src);

    // Invariant 1: en/zh leaf keys must match exactly
    let only_en: Vec<_> = en_keys.difference(&zh_keys).collect();
    let only_zh: Vec<_> = zh_keys.difference(&en_keys).collect();
    assert!(
        only_en.is_empty() && only_zh.is_empty(),
        "en/zh key mismatch\n  only en: {only_en:?}\n  only zh: {only_zh:?}"
    );

    // Invariant 2: every literal t! key in the source must exist in en and zh
    let mut src_files = Vec::new();
    collect_rs_files(&Path::new(manifest_dir).join("src"), &mut src_files);
    collect_rs_files(
        &Path::new(manifest_dir).join("crates/libscoop/src"),
        &mut src_files,
    );
    let mut used_keys = BTreeSet::new();
    for f in &src_files {
        if let Ok(src) = fs::read_to_string(f) {
            used_keys.extend(scan_literal_t_keys(&src));
        }
    }
    let missing_en: Vec<_> = used_keys.difference(&en_keys).collect();
    let missing_zh: Vec<_> = used_keys.difference(&zh_keys).collect();
    assert!(
        missing_en.is_empty(),
        "keys used in source but missing from en.yml: {missing_en:?}"
    );
    assert!(
        missing_zh.is_empty(),
        "keys used in source but missing from zh.yml: {missing_zh:?}"
    );

    // Invariant 3 (soft): dead-key warning, does not block
    let dead: Vec<_> = en_keys
        .iter()
        .filter(|k| !k.starts_with("cli_help.") && !used_keys.contains(*k))
        .collect();
    if !dead.is_empty() {
        eprintln!(
            "[i18n warning] {} yml keys never referenced by a literal in the source \
             (may be used via a variable/Display; please confirm manually):",
            dead.len()
        );
        for k in &dead {
            eprintln!("  - {k}");
        }
    }
}

#[test]
fn i18n_consistency() {
    run_consistency();
}

/// Pins the YAML corners `crates/hok-i18n/build.rs` has to flatten the way
/// rust-i18n did. The rules are documented in that build script, but a build
/// script is never compiled as a test target, so the only way to cover them is
/// through their product: the tables the runtime exposes.
///
/// The assertions deliberately check *shape* rather than wording, so editing a
/// translation does not break them.
#[test]
fn yaml_flattening_survives_the_build_script() {
    hok_i18n::set_locale("en");

    // `|-` (literal block scalar): line breaks are kept, the final newline is
    // stripped. These blocks carry the multi-line help texts.
    let block = hok_i18n::t!("cli_help.shim.long_about");
    assert!(
        block.contains('\n'),
        "block scalar lost its line breaks: {block:?}"
    );
    assert!(
        !block.ends_with('\n'),
        "`|-` must strip the final newline: {block:?}"
    );

    // Double-quoted scalar: `\n` is an escape and must be decoded, never left
    // in the rendered text as a literal backslash-n.
    let escaped = hok_i18n::t!("cli_help.alias.long_about");
    assert!(
        escaped.contains('\n'),
        "escaped newline was not decoded: {escaped:?}"
    );
    assert!(
        !escaped.contains("\\n"),
        "escape sequence leaked into the text: {escaped:?}"
    );

    // Flow sequence: no single string form exists. rust-i18n collapsed these to
    // the empty string, and the `cli_alias.*` entries (shell completions) rely
    // on that shape rather than on rendering `[s]`.
    assert_eq!(hok_i18n::t!("cli_alias.search"), "");
    assert_eq!(hok_i18n::t!("cli_alias.bucket.List"), "");
}

// ── Invariant 5: every documented long description has a `long_about` key ────

/// `(variant, module, paragraphs)` for every `Command` variant shaped
/// `Name(module::Args)` — the shape `hok-i18n-derive` treats as a command and
/// resolves to `src/cmd/<module>.rs`.
fn command_variants(mod_src: &str) -> Vec<(String, String, Vec<String>)> {
    let lines: Vec<&str> = mod_src.lines().collect();
    let mut out = Vec::new();
    for (i, raw) in lines.iter().enumerate() {
        let line = raw.trim();
        if line.starts_with("//") || line.starts_with('#') {
            continue;
        }
        let Some(open) = line.find('(') else { continue };
        let variant = &line[..open];
        if !variant
            .chars()
            .next()
            .is_some_and(|c| c.is_ascii_uppercase())
            || !variant.chars().all(|c| c.is_ascii_alphanumeric())
        {
            continue;
        }
        let inner = line[open + 1..].trim();
        let Some(close) = inner.find("::Args") else {
            continue;
        };
        let module = inner[..close].trim();
        if module.is_empty()
            || !module
                .chars()
                .all(|c| c.is_ascii_lowercase() || c == '_' || c.is_ascii_digit())
        {
            continue;
        }
        out.push((
            variant.to_string(),
            module.to_string(),
            doc_paragraphs(&lines, i),
        ));
    }
    out
}

/// Doc-comment paragraphs of the item declared on `lines[item]`, flattened to
/// one line per paragraph. Walks back over the `///` lines and skips the
/// `#[...]` attribute lines that may sit between them and the item.
fn doc_paragraphs(lines: &[&str], item: usize) -> Vec<String> {
    let mut doc: Vec<String> = Vec::new();
    let mut i = item;
    while i > 0 {
        let prev = lines[i - 1].trim_start();
        if let Some(text) = prev.strip_prefix("///") {
            doc.push(text.trim().to_string());
            i -= 1;
        } else if prev.starts_with("#[") {
            i -= 1;
        } else {
            break;
        }
    }
    doc.reverse();

    let mut paragraphs = Vec::new();
    let mut current = String::new();
    for line in doc {
        if line.is_empty() {
            if !current.is_empty() {
                paragraphs.push(std::mem::take(&mut current));
            }
        } else {
            if !current.is_empty() {
                current.push(' ');
            }
            current.push_str(&line);
        }
    }
    if !current.is_empty() {
        paragraphs.push(current);
    }
    paragraphs
}

/// Doc-comment paragraphs of the command's `Args` struct, if it declares one.
fn args_doc_paragraphs(src: &str) -> Vec<String> {
    let lines: Vec<&str> = src.lines().collect();
    for (i, raw) in lines.iter().enumerate() {
        let line = raw.trim_start();
        if line.starts_with("pub struct Args") || line.starts_with("pub(crate) struct Args") {
            return doc_paragraphs(&lines, i);
        }
    }
    Vec::new()
}

/// `(variant, paragraphs)` for the nested subcommand variants of one command
/// file. Variants are indented by exactly four spaces and start with an
/// upper-case letter; struct fields share the indent but start lower-case.
fn nested_variants(src: &str) -> Vec<(String, Vec<String>)> {
    let lines: Vec<&str> = src.lines().collect();
    let mut out = Vec::new();
    for (i, raw) in lines.iter().enumerate() {
        if !raw.starts_with("    ") || raw.starts_with("     ") {
            continue;
        }
        let line = raw.trim_start();
        let name: String = line
            .chars()
            .take_while(|c| c.is_ascii_alphanumeric())
            .collect();
        if !name.chars().next().is_some_and(|c| c.is_ascii_uppercase()) {
            continue;
        }
        let rest = &line[name.len()..];
        if !(rest.starts_with('{') || rest.starts_with('(') || rest.starts_with(',')) {
            continue;
        }
        let paragraphs = doc_paragraphs(&lines, i);
        if paragraphs.len() > 1 {
            out.push((name, paragraphs));
        }
    }
    out
}

/// `CiAutoPr` -> `ci-auto-pr`, matching the derive's key conversion.
fn to_kebab(name: &str) -> String {
    let mut out = String::with_capacity(name.len() + 2);
    for (i, c) in name.char_indices() {
        if i > 0 && c.is_ascii_uppercase() {
            out.push('-');
        }
        out.push(c.to_ascii_lowercase());
    }
    out
}

/// The derive patches `long_about` with the translated short `about` whenever
/// the `long_about` key is missing, so a doc comment that documents a long
/// description silently renders in neither locale unless the key exists. This
/// walks every command (and every nested subcommand) and requires the key in
/// both tables — how `create`, `search`, `auto_pr`, `virustotal` and
/// `shim add` lost theirs.
#[test]
fn documented_long_help_is_translated() {
    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let read = |file: &str| {
        fs::read_to_string(manifest_dir.join(file))
            .unwrap_or_else(|e| panic!("cannot read {file}: {e}"))
    };
    let en_keys = extract_leaf_keys(&read("locales/en.yml"));
    let zh_keys = extract_leaf_keys(&read("locales/zh.yml"));
    let mod_src = read("src/cmd/mod.rs");

    let mut failures = Vec::new();
    let mut checked = 0usize;
    let require = |key: &str, source: &str, failures: &mut Vec<String>| {
        for (locale, keys) in [("en", &en_keys), ("zh", &zh_keys)] {
            if !keys.contains(key) {
                failures.push(format!(
                    "{locale}.yml: missing `{key}` (documented in {source})"
                ));
            }
        }
    };

    for (_variant, module, variant_doc) in command_variants(&mod_src) {
        let file = format!("src/cmd/{module}.rs");
        let Ok(src) = fs::read_to_string(manifest_dir.join(&file)) else {
            continue;
        };
        // Either doc comment can carry the long description: clap renders the
        // `Args` struct's second paragraph, and the variant's own doc is the
        // fallback the derive overrides.
        let args_doc = args_doc_paragraphs(&src);
        if variant_doc.len() > 1 || args_doc.len() > 1 {
            checked += 1;
            require(
                &format!("cli_help.{module}.long_about"),
                &file,
                &mut failures,
            );
        }
        for (variant, paragraphs) in nested_variants(&src) {
            checked += 1;
            require(
                &format!("cli_help.{module}.args.{}.long_about", to_kebab(&variant)),
                &format!("{file} ({variant}, {} paragraphs)", paragraphs.len()),
                &mut failures,
            );
        }
    }

    assert!(
        checked >= 5,
        "the scanner found only {checked} documented long descriptions; if the \
         source layout changed, fix the scanner instead of letting this guard go vacuous"
    );
    assert!(
        failures.is_empty(),
        "{} documented long description(s) without a translation key:\n{}",
        failures.len(),
        failures.join("\n")
    );
}
